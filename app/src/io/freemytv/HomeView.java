    /** No cards on screen: none loaded, or the recommendations are off (then they are loaded but hidden). */
    private boolean noCards() {
        if (isSportsTab()) return false;
        if (Prefs.photoLayout() || !picksOn()) return true;
        return cards.isEmpty();
    }

    private boolean moveLight(int dx, int dy) {
        switch (zone) {
            case Z_SHELF:
                // Up from an empty shelf too: move()'s older zones (the hero, the corner capsule) aren't drawn any more.
                if (dy >= 0) return false;
                if (noCards()) {
                    if (!contentOn() && lightButtons.isEmpty()) return true;   // no tabs and no buttons above
                    zone = Z_TOP;
                    topIndex = contentOn() ? tab : tabsCount();
                } else {
                    zone = Z_CARDS;
                    if (isSportsTab()) {
                        cardIndex = 0;
                    } else {
                        cardIndex = nearest(cardRects, cards.size(), shelf.isEmpty() ? w / 2f : tileRects[shelfIndex].centerX());
                    }
                }
                break;
            case Z_CARDS:
                if (isSportsTab()) {
                    if (dy < 0) {
                        zone = Z_TOP;
                        topIndex = tab;
                    } else if (dy > 0) {
                        zone = Z_SHELF;
                        if (!shelf.isEmpty()) shelfIndex = nearest(tileRects, tileRects.length, sportsHeroCard.centerX());
                    } else {
                        return true;
                    }
                } else {
                    if (dx != 0) {
                        int next = Math.max(0, Math.min(cards.size() - 1, cardIndex + dx));
                        if (next == cardIndex) return true;
                        cardIndex = next;
                        followCard();
                    } else if (dy < 0) {
                        zone = Z_TOP;
                        topIndex = tab;     // as on Apple TV: moving up to the tabs focuses the selected tab
                    } else {
                        zone = Z_SHELF;
                        if (!shelf.isEmpty()) shelfIndex = nearest(tileRects, tileRects.length, cardRects[cardIndex].centerX());
                    }
                }
                break;
            case Z_TOP: {
                int tc = tabsCount();
                if (dx != 0) {
                    int next = Math.max(contentOn() ? 0 : tc, Math.min((tc - 1) + lightButtons.size(), topIndex + dx));
                    if (next == topIndex) return true;
                    topIndex = next;
                    if (topIndex < tc) selectTab(topIndex);   // like Apple TV tabs: focusing a tab selects it
                } else if (dy > 0) {
                    if (noCards()) {
                        zone = Z_SHELF;
                    } else {
                        zone = Z_CARDS;
                        if (isSportsTab()) {
                            cardIndex = 0;
                        } else {
                            cardIndex = nearest(cardRects, cards.size(), topRects[topIndex].centerX());
                        }
                    }
                } else if (topIndex < tc && !lightButtons.isEmpty()) {
                    topIndex = tc;   // up from the tabs reaches the corner buttons without walking the row
                } else {
                    return true;
                }
                break;
            }
            default:
                return false;
        }
        retarget(false);
        click.move();
        return true;
    }

    private static int nearest(RectF[] rects, int count, float x) {
        int best = 0;
        float bestDistance = Float.MAX_VALUE;
        for (int i = 0; i < Math.min(count, rects.length); i++) {
            float d = Math.abs(rects[i].centerX() - x);
            if (d < bestDistance) {
                bestDistance = d;
                best = i;
            }
        }
        return best;
    }

    // MARK: - Helpers

    private static float smoothstep(float e0, float e1, float x) {
        float t = Ui.clamp((x - e0) / (e1 - e0));
        return t * t * (3 - 2 * t);
    }

    private static int blend(int a, int b, float f) {
        int aa = a >>> 24, ar = (a >> 16) & 255, ag = (a >> 8) & 255, ab = a & 255;
        int ba = b >>> 24, br = (b >> 16) & 255, bg = (b >> 8) & 255, bb = b & 255;
        return (Math.round(aa + (ba - aa) * f) << 24) | (Math.round(ar + (br - ar) * f) << 16)
                | (Math.round(ag + (bg - ag) * f) << 8) | Math.round(ab + (bb - ab) * f);
    }
